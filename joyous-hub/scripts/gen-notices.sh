#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES.md: the licence texts of every module the hub
# and bridges build in on macOS, Linux and Windows, plus the C libraries and
# font bundled with them. Run after changing dependencies.
# Usage: gen-notices.sh [output]   (default: THIRD_PARTY_NOTICES.md beside go.mod)
set -euo pipefail
export LC_ALL=C # same file order on every OS

SRC_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$SRC_DIR/THIRD_PARTY_NOTICES.md}"
cd "$SRC_DIR"

modules="$(
	for os in darwin linux windows; do
		for tags in "" inkjoybridge samsungbridge nixplaybridge; do
			GOOS="$os" CGO_ENABLED=1 go list -deps -tags "$tags" \
				-f '{{with .Module}}{{if not .Main}}{{.Path}}{{end}}{{end}}' .
		done
	done | sort -u | grep -v '^$'
)"

licence_files() {
	find "$1" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' -o -iname 'edl-v10' \) | sort
}

section() { # title, file...
	local title="$1"
	shift
	printf '\n## %s\n' "$title"
	for f in "$@"; do
		printf '\n```\n'
		cat "$f"
		printf '\n```\n'
	done
}

goheif="$(go list -m -f '{{.Dir}}' github.com/jdeng/goheif)"
avif="$(go list -m -f '{{.Dir}}' github.com/gen2brain/avif)"

{
	cat <<'EOF'
# Third-party notices

Joyous is licensed under the GNU Affero General Public License v3 (see
LICENSE). Its binaries include the components below, each under its own
licence, reproduced here. Generated by `scripts/gen-notices.sh`.

**libde265** (HEVC decoding for HEIC photos, built into the binaries through
github.com/jdeng/goheif) is licensed under the GNU Lesser General Public
License v3. Its source is at https://github.com/strukturag/libde265, and the
copy built here is in the github.com/jdeng/goheif module. Joyous's own source
is published, so you may rebuild the binaries against a modified libde265.

**github.com/eclipse/paho.mqtt.golang** is dual-licensed under EPL-2.0 and the
Eclipse Distribution License 1.0 (BSD-3-Clause); Joyous uses it under the EDL.

## Go modules

| Module | Version |
|---|---|
EOF
	while read -r m; do
		printf '| %s | %s |\n' "$m" "$(go list -m -f '{{.Version}}' "$m")"
	done <<<"$modules"

	while read -r m; do
		dir="$(go list -m -f '{{.Dir}}' "$m")"
		files=()
		while IFS= read -r f; do files+=("$f"); done < <(licence_files "$dir")
		if ((${#files[@]} == 0)); then
			echo "gen-notices: no licence file in $m" >&2
			exit 1
		fi
		section "$m" "${files[@]}"
	done <<<"$modules"

	section "github.com/jdeng/goheif/heif" "$goheif/heif/LICENSE"
	section "Go standard library and runtime" "$(go env GOROOT)/LICENSE"
	section "libde265 (via github.com/jdeng/goheif)" "$goheif/libde265/libde265/COPYING"
	printf '\n## dav1d (via github.com/jdeng/goheif)\n\nBSD-2-Clause, as stated in its source headers:\n\n```\n'
	sed -n '2,25p' "$goheif/dav1d/src/itx_1d.h" | sed -E 's/^ \* ?//; s/^ \*\/$//'
	printf '```\n'
	section "libavif and aom (via github.com/gen2brain/avif)" "$avif/lib/LICENSE.libavif" "$avif/lib/LICENSE.aom"
	section "Caveat font (fonts/)" "$SRC_DIR/fonts/OFL.txt"
} >"$OUT"
echo "wrote $OUT"
